// Default Configuration
let currentBank = {
    id: 'bbl',
    name: 'Bangkok Bank',
    color: '#1e4598',
    logoText: 'BBL'
};

const canvas = document.getElementById('cardCanvas');
const ctx = canvas.getContext('2d');

// Bank Selection Logic
function selectBank(bankId, color) {
    // Update UI active state
    document.querySelectorAll('.bank-option').forEach(el => el.classList.remove('active'));
    event.target.classList.add('active');

    // Set Bank Details
    currentBank.id = bankId;
    currentBank.color = color;
    
    // Set Names for Demo (In real app, you might use images)
    if(bankId === 'bbl') { currentBank.name = 'Bangkok Bank'; currentBank.logoText = 'BBL'; }
    if(bankId === 'kbank') { currentBank.name = 'Kasikorn Bank'; currentBank.logoText = 'KBank'; }
    if(bankId === 'scb') { currentBank.name = 'SCB Bank'; currentBank.logoText = 'SCB'; }
    if(bankId === 'kbz') { currentBank.name = 'KBZ Bank'; currentBank.logoText = 'KBZ'; }

    updateCard();
}

// Main Drawing Function
function updateCard() {
    const name = document.getElementById('nameInput').value.toUpperCase() || "NAME HERE";
    const account = document.getElementById('acctInput').value || "000-000-0000";
    const theme = document.getElementById('themeSelect').value;

    // 1. Clear Canvas
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    // 2. Draw Background
    if (theme === 'gradient') {
        let grd = ctx.createLinearGradient(0, 0, 600, 0);
        grd.addColorStop(0, currentBank.color);
        grd.addColorStop(1, "#ffffff");
        ctx.fillStyle = grd;
        ctx.fillRect(0, 0, canvas.width, canvas.height);
    } else if (theme === 'modern') {
        ctx.fillStyle = "#ffffff";
        ctx.fillRect(0, 0, canvas.width, canvas.height);
        // Add a sidebar color
        ctx.fillStyle = currentBank.color;
        ctx.fillRect(0, 0, 20, canvas.height);
        // Add a header block
        ctx.fillRect(20, 0, canvas.width, 100);
    } else {
        // Solid White Background with Border style
        ctx.fillStyle = "#ffffff";
        ctx.fillRect(0, 0, canvas.width, canvas.height);
        ctx.strokeStyle = currentBank.color;
        ctx.lineWidth = 10;
        ctx.strokeRect(0, 0, canvas.width, canvas.height);
    }

    // 3. Draw Bank Logo/Text
    ctx.fillStyle = (theme === 'modern' || theme === 'gradient') ? "#ffffff" : currentBank.color;
    if(theme === 'modern') ctx.fillStyle = "#ffffff"; // Force white on header
    
    ctx.font = "bold 60px Arial";
    // Adjust position based on design
    let logoY = (theme === 'modern') ? 70 : 100;
    let logoX = (theme === 'modern') ? 50 : 50;
    
    // Simulating a Logo with Text
    ctx.fillText(currentBank.logoText, logoX, logoY);

    // Bank Full Name
    ctx.font = "bold 24px Arial";
    ctx.fillText(currentBank.name, logoX + 160, logoY - 20);
    
    // 4. Draw User Info Box
    // Draw a colored box for Name
    ctx.fillStyle = currentBank.color;
    ctx.fillRect(40, 220, 520, 60);

    // Draw Name Text
    ctx.fillStyle = "#ffffff";
    ctx.font = "bold 24px Padauk, Arial";
    ctx.textAlign = "left";
    ctx.fillText(name, 60, 258);

    // 5. Draw Account Label & Number
    ctx.fillStyle = "#333333";
    ctx.font = "bold 18px Arial";
    ctx.fillText("BANK NUMBER", 50, 180);

    ctx.font = "bold 30px Arial";
    ctx.fillStyle = "#000000";
    ctx.fillText(account, 200, 183);

    // 6. Watermark/Footer (Optional)
    ctx.font = "12px Arial";
    ctx.fillStyle = "#cccccc";
    ctx.fillText("Generated by Card Maker", 450, 330);
}

// Generate Image & Handle Download Logic
function generateImage() {
    updateCard(); // Ensure latest data is drawn

    // Convert Canvas to Data URL (Image string)
    const dataURL = canvas.toDataURL("image/png");

    // Show the image element
    const imgObj = document.getElementById('resultImage');
    imgObj.src = dataURL;
    imgObj.style.display = 'block';
    
    // Hide placeholder, show download section
    document.getElementById('placeholderText').style.display = 'none';
    document.getElementById('cardCanvas').style.display = 'none'; // Keep canvas hidden
    document.getElementById('downloadSection').style.display = 'block';

    // Handle "Download" button for standard browsers
    const dlLink = document.getElementById('downloadLink');
    dlLink.href = dataURL;
    dlLink.download = `BankCard_${currentBank.id}.png`;
}

// Initialize on load
window.onload = function() {
    updateCard();
}
